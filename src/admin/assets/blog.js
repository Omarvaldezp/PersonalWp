/**
 * Blog Posts Management
 * JavaScript para la gestión completa de posts del blog
 */

// Estado global
let currentPage = 1;
let currentFilters = {
    search: '',
    categoria: '',
    estado: ''
};
let currentSort = {
    field: 'fecha_publicacion',
    direction: 'DESC'
};
let postToDelete = null;
let totalPosts = 0;

// API Base URL
const API_BASE = '/api/controllers/blog.php';

// ============================================
// INICIALIZACIÓN
// ============================================

document.addEventListener('DOMContentLoaded', () => {
    console.log('Blog Management initialized');

    // Cargar posts iniciales
    loadPosts();

    // Cargar categorías para el filtro
    loadCategories();

    // Setup event listeners
    setupEventListeners();

    // Mostrar welcome alert si es primera vez
    showWelcomeAlert();
});

// ============================================
// SETUP
// ============================================

function setupEventListeners() {
    // Auto-generar slug desde título
    document.getElementById('titulo').addEventListener('input', (e) => {
        const slugInput = document.getElementById('slug');
        // Solo auto-generar si el slug está vacío o si coincide con el título anterior
        if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
            slugInput.value = generateSlug(e.target.value);
            slugInput.dataset.autoGenerated = 'true';
        }
    });

    // Si el usuario edita manualmente el slug, deshabilitar auto-generación
    document.getElementById('slug').addEventListener('input', (e) => {
        if (e.target.value) {
            e.target.dataset.autoGenerated = 'false';
        }
    });

    // Validar slug mientras se escribe
    document.getElementById('slug').addEventListener('input', (e) => {
        e.target.value = e.target.value
            .toLowerCase()
            .replace(/[^a-z0-9-]/g, '-')
            .replace(/-+/g, '-')
            .replace(/^-|-$/g, '');
    });

    // Search con debounce
    let searchTimeout;
    document.getElementById('searchInput').addEventListener('input', () => {
        clearTimeout(searchTimeout);
        searchTimeout = setTimeout(() => {
            currentFilters.search = document.getElementById('searchInput').value;
            loadPosts(1);
        }, 500);
    });

    // Sorting en columnas
    document.querySelectorAll('th[sortable]').forEach(th => {
        th.addEventListener('click', () => {
            const sortField = th.dataset.sort;

            // Toggle direction si es el mismo campo
            if (currentSort.field === sortField) {
                currentSort.direction = currentSort.direction === 'ASC' ? 'DESC' : 'ASC';
            } else {
                currentSort.field = sortField;
                currentSort.direction = 'DESC';
            }

            // Actualizar UI
            document.querySelectorAll('th[sortable]').forEach(t => {
                t.classList.remove('sorted-asc', 'sorted-desc');
            });
            th.classList.add(currentSort.direction === 'ASC' ? 'sorted-asc' : 'sorted-desc');

            // Recargar posts
            loadPosts(currentPage);
        });
    });

    // Character counter para extracto
    const extracto = document.getElementById('extracto');
    const contador = document.createElement('span');
    contador.className = 'form-hint';
    contador.style.float = 'right';
    extracto.parentNode.appendChild(contador);

    extracto.addEventListener('input', () => {
        const length = extracto.value.length;
        const max = extracto.maxLength;
        contador.textContent = `${length}/${max} caracteres`;
        contador.style.color = length > max * 0.9 ? 'var(--danger)' : 'var(--gray-500)';
    });
}

// ============================================
// CARGAR POSTS
// ============================================

async function loadPosts(page = 1) {
    showLoading(true);
    currentPage = page;

    try {
        const params = new URLSearchParams({
            page: page,
            per_page: 20,
            estado: currentFilters.estado || '',
            categoria: currentFilters.categoria || '',
            search: currentFilters.search || '',
            order_by: currentSort.field,
            order_dir: currentSort.direction
        });

        const response = await fetch(`${API_BASE}?${params}`);
        const result = await response.json();

        if (result.success) {
            renderPosts(result.data.posts || []);
            renderPagination(result.data);
            totalPosts = result.data.total || 0;
            updateStatsDisplay();
        } else {
            showToast(result.message || 'Error al cargar posts', 'error');
        }
    } catch (error) {
        console.error('Error loading posts:', error);
        showToast('Error de conexión al cargar posts', 'error');
    } finally {
        showLoading(false);
    }
}

// ============================================
// RENDERIZAR POSTS
// ============================================

function renderPosts(posts) {
    const tbody = document.getElementById('postsTableBody');
    const emptyState = document.getElementById('emptyState');
    const table = document.getElementById('postsTable');

    if (posts.length === 0) {
        tbody.innerHTML = '';
        table.style.display = 'none';
        emptyState.style.display = 'flex';
        document.getElementById('pagination').style.display = 'none';
        return;
    }

    table.style.display = 'table';
    emptyState.style.display = 'none';
    document.getElementById('pagination').style.display = 'flex';

    tbody.innerHTML = posts.map(post => `
        <tr>
            <td>
                <div class="post-title">
                    <strong>${escapeHtml(post.titulo)}</strong>
                    <small>${escapeHtml(post.slug)}</small>
                </div>
            </td>
            <td>
                ${(post.categorias || []).map(cat =>
                    `<span class="badge badge-primary">${escapeHtml(cat)}</span>`
                ).join(' ')}
            </td>
            <td>
                <span class="status status-${post.estado}">
                    ${post.estado}
                </span>
            </td>
            <td>${formatNumber(post.visitas || 0)}</td>
            <td>${formatDate(post.fecha_publicacion || post.created_at)}</td>
            <td>
                <div class="action-buttons">
                    <button onclick="editPost(${post.id})"
                            class="btn-icon"
                            title="Editar">
                        ✏
                    </button>
                    <button onclick="previewPost(${post.id})"
                            class="btn-icon"
                            title="Vista previa">
                        👁
                    </button>
                    <button onclick="deletePost(${post.id}, '${escapeHtml(post.titulo).replace(/'/g, "\\'")}' )"
                            class="btn-icon btn-danger"
                            title="Eliminar">
                        🗑
                    </button>
                </div>
            </td>
        </tr>
    `).join('');
}

// ============================================
// PAGINATION
// ============================================

function renderPagination(data) {
    const container = document.getElementById('pagination');
    const { page, total_pages, total } = data;

    if (total_pages <= 1) {
        container.innerHTML = '';
        return;
    }

    const prevDisabled = page === 1 ? 'disabled' : '';
    const nextDisabled = page === total_pages ? 'disabled' : '';

    container.innerHTML = `
        <button onclick="loadPosts(${page - 1})"
                ${prevDisabled}
                class="page-btn">
            ← Anterior
        </button>
        <span class="page-info">
            Página ${page} de ${total_pages} (${total} posts)
        </span>
        <button onclick="loadPosts(${page + 1})"
                ${nextDisabled}
                class="page-btn">
            Siguiente →
        </button>
    `;
}

// ============================================
// CARGAR CATEGORÍAS
// ============================================

async function loadCategories() {
    try {
        const response = await fetch(`${API_BASE}?action=categories`);
        const result = await response.json();

        if (result.success && result.data) {
            const select = document.getElementById('categoriaFilter');
            const categories = Array.isArray(result.data) ? result.data : [];

            categories.forEach(cat => {
                const option = document.createElement('option');
                option.value = cat;
                option.textContent = cat;
                select.appendChild(option);
            });
        }
    } catch (error) {
        console.error('Error loading categories:', error);
    }
}

// ============================================
// FILTROS
// ============================================

function applyFilters() {
    currentFilters.search = document.getElementById('searchInput').value;
    currentFilters.categoria = document.getElementById('categoriaFilter').value;
    currentFilters.estado = document.getElementById('estadoFilter').value;
    loadPosts(1);
}

function clearFilters() {
    document.getElementById('searchInput').value = '';
    document.getElementById('categoriaFilter').value = '';
    document.getElementById('estadoFilter').value = '';
    currentFilters = { search: '', categoria: '', estado: '' };
    loadPosts(1);
}

// ============================================
// CREAR POST
// ============================================

function openCreateModal() {
    document.getElementById('modalTitle').textContent = 'Nuevo Post';
    document.getElementById('postForm').reset();
    document.getElementById('postId').value = '';

    // Reset validation states
    document.querySelectorAll('#postForm input, #postForm textarea, #postForm select').forEach(field => {
        field.classList.remove('error', 'valid');
    });
    document.querySelectorAll('#postForm .error-message').forEach(el => el.remove());

    // Set default estado
    document.getElementById('estado').value = 'borrador';

    // Reset auto-generated flag
    document.getElementById('slug').dataset.autoGenerated = 'true';

    openModal('postModal');
}

// ============================================
// EDITAR POST
// ============================================

async function editPost(id) {
    try {
        const response = await fetch(`${API_BASE}?id=${id}`);
        const result = await response.json();

        if (result.success && result.data) {
            const post = result.data;

            document.getElementById('modalTitle').textContent = 'Editar Post';
            document.getElementById('postId').value = post.id;
            document.getElementById('titulo').value = post.titulo;
            document.getElementById('slug').value = post.slug;
            document.getElementById('slug').dataset.autoGenerated = 'false';
            document.getElementById('extracto').value = post.extracto || '';
            document.getElementById('contenido').value = post.contenido;
            document.getElementById('imagen_portada').value = post.imagen_portada || '';
            document.getElementById('categorias').value = (post.categorias || []).join(', ');
            document.getElementById('etiquetas').value = (post.etiquetas || []).join(', ');
            document.getElementById('estado').value = post.estado;

            if (post.fecha_publicacion) {
                const date = new Date(post.fecha_publicacion);
                const localDateTime = new Date(date.getTime() - date.getTimezoneOffset() * 60000)
                    .toISOString()
                    .slice(0, 16);
                document.getElementById('fecha_publicacion').value = localDateTime;
            } else {
                document.getElementById('fecha_publicacion').value = '';
            }

            // Trigger character counter
            document.getElementById('extracto').dispatchEvent(new Event('input'));

            openModal('postModal');
        } else {
            showToast(result.message || 'Error al cargar el post', 'error');
        }
    } catch (error) {
        console.error('Error loading post:', error);
        showToast('Error de conexión al cargar el post', 'error');
    }
}

// ============================================
// GUARDAR POST
// ============================================

async function savePost() {
    const form = document.getElementById('postForm');

    // Validar formulario
    if (!validateForm(form)) {
        showToast('Por favor corrige los errores en el formulario', 'error');
        return;
    }

    const postId = document.getElementById('postId').value;
    const isEdit = postId !== '';

    // Preparar datos
    const data = {
        titulo: document.getElementById('titulo').value.trim(),
        slug: document.getElementById('slug').value.trim(),
        extracto: document.getElementById('extracto').value.trim() || null,
        contenido: document.getElementById('contenido').value.trim(),
        imagen_portada: document.getElementById('imagen_portada').value.trim() || null,
        categorias: document.getElementById('categorias').value
            .split(',')
            .map(s => s.trim())
            .filter(s => s),
        etiquetas: document.getElementById('etiquetas').value
            .split(',')
            .map(s => s.trim())
            .filter(s => s),
        estado: document.getElementById('estado').value,
        fecha_publicacion: document.getElementById('fecha_publicacion').value || null
    };

    // Si no hay fecha y el estado es publicado, usar fecha actual
    if (!data.fecha_publicacion && data.estado === 'publicado') {
        data.fecha_publicacion = new Date().toISOString().slice(0, 19).replace('T', ' ');
    }

    // Mostrar loading en botón
    const saveBtn = document.getElementById('savePostBtn');
    setButtonLoading(saveBtn, true);

    try {
        const url = isEdit ? `${API_BASE}?id=${postId}` : API_BASE;
        const method = isEdit ? 'PUT' : 'POST';

        const response = await fetch(url, {
            method: method,
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify(data)
        });

        const result = await response.json();

        if (result.success) {
            showToast(
                isEdit ? 'Post actualizado correctamente' : 'Post creado correctamente',
                'success'
            );
            closePostModal();
            loadPosts(currentPage);
        } else {
            showToast(result.message || 'Error al guardar el post', 'error');
        }
    } catch (error) {
        console.error('Error saving post:', error);
        showToast('Error de conexión al guardar el post', 'error');
    } finally {
        setButtonLoading(saveBtn, false);
    }
}

// ============================================
// ELIMINAR POST
// ============================================

function deletePost(id, title) {
    postToDelete = id;
    document.getElementById('deletePostTitle').textContent = title;
    openModal('deleteModal');
}

async function confirmDelete() {
    if (!postToDelete) return;

    const confirmBtn = document.getElementById('confirmDeleteBtn');
    setButtonLoading(confirmBtn, true);

    try {
        const response = await fetch(`${API_BASE}?id=${postToDelete}`, {
            method: 'DELETE'
        });

        const result = await response.json();

        if (result.success) {
            showToast('Post eliminado correctamente', 'success');
            closeDeleteModal();
            loadPosts(currentPage);
        } else {
            showToast(result.message || 'Error al eliminar el post', 'error');
        }
    } catch (error) {
        console.error('Error deleting post:', error);
        showToast('Error de conexión al eliminar el post', 'error');
    } finally {
        setButtonLoading(confirmBtn, false);
    }
}

// ============================================
// VISTA PREVIA
// ============================================

async function previewPost(id) {
    try {
        const response = await fetch(`${API_BASE}?id=${id}`);
        const result = await response.json();

        if (result.success && result.data) {
            const post = result.data;

            const previewContent = document.getElementById('previewContent');
            previewContent.innerHTML = `
                <article style="max-width: 800px; margin: 0 auto;">
                    ${post.imagen_portada ? `
                        <img src="${escapeHtml(post.imagen_portada)}"
                             alt="${escapeHtml(post.titulo)}"
                             style="width: 100%; height: auto; border-radius: 8px; margin-bottom: 2rem;">
                    ` : ''}

                    <h1 style="font-size: 2.5rem; margin-bottom: 1rem;">${escapeHtml(post.titulo)}</h1>

                    <div style="display: flex; gap: 1rem; margin-bottom: 2rem; color: var(--gray-600); font-size: 0.875rem;">
                        <span>Por: ${escapeHtml(post.autor_nombre || 'Admin')}</span>
                        <span>•</span>
                        <span>${formatDate(post.fecha_publicacion || post.created_at)}</span>
                        <span>•</span>
                        <span>${formatNumber(post.visitas || 0)} visitas</span>
                    </div>

                    ${post.categorias && post.categorias.length > 0 ? `
                        <div style="margin-bottom: 2rem;">
                            ${post.categorias.map(cat =>
                                `<span class="badge badge-primary">${escapeHtml(cat)}</span>`
                            ).join(' ')}
                        </div>
                    ` : ''}

                    ${post.extracto ? `
                        <p style="font-size: 1.25rem; color: var(--gray-700); margin-bottom: 2rem; font-style: italic;">
                            ${escapeHtml(post.extracto)}
                        </p>
                    ` : ''}

                    <div style="line-height: 1.8; color: var(--gray-800);">
                        ${escapeHtml(post.contenido).replace(/\n/g, '<br>')}
                    </div>

                    ${post.etiquetas && post.etiquetas.length > 0 ? `
                        <div style="margin-top: 3rem; padding-top: 2rem; border-top: 1px solid var(--gray-200);">
                            <strong style="color: var(--gray-600); font-size: 0.875rem;">Etiquetas:</strong>
                            ${post.etiquetas.map(tag =>
                                `<span class="badge">${escapeHtml(tag)}</span>`
                            ).join(' ')}
                        </div>
                    ` : ''}
                </article>
            `;

            openModal('previewModal');
        } else {
            showToast(result.message || 'Error al cargar vista previa', 'error');
        }
    } catch (error) {
        console.error('Error loading preview:', error);
        showToast('Error de conexión al cargar vista previa', 'error');
    }
}

// ============================================
// MODAL HELPERS
// ============================================

function closePostModal() {
    closeModal('postModal');
}

function closeDeleteModal() {
    closeModal('deleteModal');
    postToDelete = null;
}

function closePreviewModal() {
    closeModal('previewModal');
}

// ============================================
// UI HELPERS
// ============================================

function showLoading(show) {
    const loadingState = document.getElementById('loadingState');
    const table = document.getElementById('postsTable');

    if (show) {
        loadingState.style.display = 'flex';
        table.style.opacity = '0.5';
    } else {
        loadingState.style.display = 'none';
        table.style.opacity = '1';
    }
}

function updateStatsDisplay() {
    // Actualizar algún indicador si existe
    const statsText = document.querySelector('.stats-text');
    if (statsText) {
        statsText.textContent = `Total: ${totalPosts} posts`;
    }
}

function showWelcomeAlert() {
    const hasSeenWelcome = localStorage.getItem('blog_welcome_seen');
    if (!hasSeenWelcome) {
        document.getElementById('welcomeAlert').style.display = 'flex';
    }
}

function dismissWelcome() {
    localStorage.setItem('blog_welcome_seen', 'true');
    document.getElementById('welcomeAlert').remove();
}

