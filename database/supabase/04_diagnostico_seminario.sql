-- ============================================================================
-- Diagnóstico inicial del Seminario de Investigación Teórico (DISDE, 2026-2)
--
-- CÓRRELO DESPUÉS DE 00_roles.sql. Las políticas del final usan tiene_rol().
-- No depende de 01_academico.sql: puede correrse antes o después.
--
-- De dónde sale este diseño:
--   BACKEND.md proponía dos tablas —la respuesta completa y el desglose de las
--   escalas numéricas— con un endpoint PHP en medio. Las dos tablas se
--   conservan porque la idea es buena: sacar promedios de un JSON es incómodo
--   y lento. Lo que cambia es el resto, para que encaje con lo que ya tienes:
--
--     PHP en hosting compartido  ->  Supabase, como el resto del sitio
--     endpoint que valida        ->  función guardar_diagnostico_seminario()
--     tabla abierta al público   ->  ninguna política para anon
--
--   El formulario no escribe en las tablas. Llama a la función, y la función
--   es la única que escribe. Así el visitante puede contestar sin que la
--   llave anónima —que está a la vista en el código del sitio— sirva para
--   leer, modificar ni borrar nada.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- Utilidad: convertir un valor JSON en text[]
--
-- Los grupos de casillas llegan como arreglo, pero si el navegador manda una
-- sola marca puede llegar como cadena suelta. Esto normaliza los dos casos y
-- el nulo.
-- ---------------------------------------------------------------------------
create or replace function public.jsonb_a_texto_array(j jsonb)
returns text[]
language sql
immutable
as $$
    select case
        when j is null or jsonb_typeof(j) = 'null'  then '{}'::text[]
        when jsonb_typeof(j) = 'array'              then array(select jsonb_array_elements_text(j))
        else array[j #>> '{}']
    end;
$$;


-- ---------------------------------------------------------------------------
-- 1. La respuesta
--
-- Se promueven a columna los datos que se usan para listar, filtrar y ordenar.
-- Todo lo demás —los textos largos, los arreglos de casillas, las escalas—
-- vive íntegro en payload. Ninguna respuesta se pierde por no tener columna.
-- ---------------------------------------------------------------------------
create table if not exists public.seminario_diagnostico (
    id                bigint generated by default as identity primary key,
    ciclo             text not null,
    curso             text not null,
    nombre            text not null,
    correo            text not null,
    telefono          text,
    generacion        text,
    dedicacion        text,
    horas_semana      smallint check (horas_semana between 0 and 80),
    licenciatura_area text,
    maestria_area     text,
    director          text,
    titulo            text,
    pregunta_central  text,
    enfoque           text,
    ia_frecuencia     text,
    nps               smallint check (nps between 0 and 10),
    consentimiento    boolean not null default false,
    payload           jsonb not null default '{}'::jsonb,
    navegador         text,
    envios            integer not null default 1,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    unique (ciclo, correo)
);

create index if not exists idx_sd_ciclo   on public.seminario_diagnostico (ciclo);
create index if not exists idx_sd_fecha   on public.seminario_diagnostico (created_at desc);
create index if not exists idx_sd_correo  on public.seminario_diagnostico (correo);
create index if not exists idx_sd_payload on public.seminario_diagnostico using gin (payload);

comment on table public.seminario_diagnostico
    is 'Respuestas del diagnóstico inicial del seminario. Una por alumno y ciclo.';
comment on column public.seminario_diagnostico.payload
    is 'La respuesta íntegra tal como la mandó el formulario, incluidos los campos sin columna propia.';
comment on column public.seminario_diagnostico.envios
    is 'Cuántas veces se ha guardado esta respuesta. Mayor que 1 significa que el alumno la corrigió.';


-- ---------------------------------------------------------------------------
-- 2. El desglose de las escalas numéricas
--
-- Tres matrices del formulario: avance por componente (0 a 4), autodiagnóstico
-- de competencias (1 a 5) y satisfacción con el programa (1 a 5). Aquí cada
-- casilla es una fila, que es lo que permite sacar promedios por reactivo sin
-- pelearse con el JSON.
--
-- La llena la función a partir del payload. No se escribe a mano.
-- ---------------------------------------------------------------------------
create table if not exists public.seminario_diagnostico_item (
    respuesta_id  bigint   not null references public.seminario_diagnostico (id) on delete cascade,
    grupo         text     not null check (grupo in ('avance', 'competencia', 'satisfaccion')),
    clave         text     not null,
    valor         smallint not null check (valor between 0 and 10),
    primary key (respuesta_id, clave)
);

create index if not exists idx_sdi_grupo on public.seminario_diagnostico_item (grupo, clave);


